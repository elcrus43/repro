export function getDeveloperKnowledge(developerName) {
  if (!developerName) return null;
  const target = String(developerName).trim().toLowerCase();
  return (
    DEVELOPERS_KNOWLEDGE.find((item) => {
      const name = item.name.toLowerCase();
      const shortName = item.shortName.toLowerCase();
      return (
        name === target ||
        shortName === target ||
        name.includes(target) ||
        target.includes(shortName)
      );
    }) || null
  );
}

export function getStoredDeveloperNotes() {
  if (typeof window === 'undefined') return {};
  try {
    const raw = localStorage.getItem(KB_NOTES_STORAGE_KEY);
    const parsed = raw ? JSON.parse(raw) : {};
    return parsed && typeof parsed === 'object' ? parsed : {};
  } catch {
    return {};
  }
}

export function saveDeveloperNote(developerId, noteText) {
  if (typeof window === 'undefined' || !developerId) return {};
  const current = getStoredDeveloperNotes();
  const next = { ...current };
  const trimmed = String(noteText || '').trim();
  if (trimmed) {
    next[developerId] = {
      text: trimmed,
      updatedAt: new Date().toISOString(),
    };
  } else {
    delete next[developerId];
  }
  try {
    localStorage.setItem(KB_NOTES_STORAGE_KEY, JSON.stringify(next));
  } catch {
    // ignore quota errors
  }
  return next;
}
